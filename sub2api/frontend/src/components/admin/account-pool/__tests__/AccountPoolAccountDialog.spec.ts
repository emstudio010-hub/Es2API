import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import AccountPoolAccountDialog from '../AccountPoolAccountDialog.vue'
import { account, group } from './fixtures'
const { importAccount, updateAccount } = vi.hoisted(() => ({ importAccount: vi.fn(), updateAccount: vi.fn() }))
const { generateAuthUrl, exchangeCode } = vi.hoisted(() => ({ generateAuthUrl: vi.fn(), exchangeCode: vi.fn() }))
vi.mock('@/api/admin/integrationAccounts', () => ({ importIntegrationAccount: importAccount, updateIntegrationAccount: updateAccount }))
vi.mock('@/api/admin/accounts', () => ({ generateAuthUrl, exchangeCode }))
vi.mock('@/api/admin/integrationClient', () => ({ integrationErrorMessage: (_: unknown, fallback: string) => fallback }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
const base = { template: '<section v-if="show"><slot/><slot name="footer"/></section>', props: ['show'], emits: ['close'] }
const wrappers: ReturnType<typeof mount>[] = []
function create(editing = false) {
  const wrapper = mount(AccountPoolAccountDialog, { props: { show: true, groups: [group], account: editing ? account() : null }, global: { stubs: { BaseDialog: base } } })
  wrappers.push(wrapper)
  return wrapper
}
async function chooseProxy(wrapper: ReturnType<typeof create>) {
  await wrapper.findAll('input')[2].setValue('proxy-test')
}
beforeEach(() => { importAccount.mockReset(); updateAccount.mockReset(); generateAuthUrl.mockReset(); exchangeCode.mockReset(); localStorage.clear(); sessionStorage.clear() })
afterEach(() => { wrappers.forEach(wrapper => wrapper.unmount()); wrappers.length = 0 })
describe('account pool import and edit lifecycle', () => {
  it('rejects API keys and malformed OAuth locally without a network call', async () => {
    const wrapper = create()
    await wrapper.find('input').setValue('New account')
    await chooseProxy(wrapper)
    for (const [value, expected] of [['{', 'invalidJson'], ['{"api_key":"test-key"}', 'apiKeyUnsupported'], ['{"id_token":"test-id"}', 'invalidCredential']]) {
      await wrapper.get('textarea').setValue(value)
      await wrapper.get('form').trigger('submit')
      expect(wrapper.get('[role="alert"]').text()).toContain(expected)
    }
    expect(importAccount).not.toHaveBeenCalled()
  })
  it('clears OAuth on success and does not store it persistently', async () => {
    const wrapper = create()
    importAccount.mockResolvedValue(account())
    await wrapper.find('input').setValue('New account')
    await chooseProxy(wrapper)
    await wrapper.get('textarea').setValue('{"tokens":{"access_token":"test-only-secret"}}')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(importAccount.mock.calls[0][0].credential).toEqual({ tokens: { access_token: 'test-only-secret' } })
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
    expect(wrapper.emitted('saved')).toHaveLength(1)
    expect(wrapper.emitted('close')).toEqual([[false]])
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
  })
  it('clears on close and ignores a late import response from a previous dialog', async () => {
    let resolve: (value: ReturnType<typeof account>) => void = () => {}
    importAccount.mockReturnValue(new Promise(value => { resolve = value }))
    const wrapper = create()
    await wrapper.find('input').setValue('New account')
    await chooseProxy(wrapper)
    await wrapper.get('textarea').setValue('{"access_token":"test-only-secret"}')
    await wrapper.get('form').trigger('submit')
    const signal = importAccount.mock.calls[0][2] as AbortSignal
    await wrapper.get('[data-testid="account-pool-close"]').trigger('click')
    expect(signal.aborted).toBe(true)
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
    expect(wrapper.emitted('close')).toEqual([[true]])
    await wrapper.setProps({ show: false })
    await wrapper.setProps({ show: true })
    resolve(account())
    await flushPromises()
    expect(wrapper.emitted('saved')).toBeUndefined()
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
  })
  it('omits unchanged binding fields so priority edits do not rebuild slots', async () => {
    const wrapper = create(true)
    updateAccount.mockResolvedValue(account({ priority: 20 }))
    await wrapper.findAll('input[type="number"]')[1].setValue('20')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(updateAccount.mock.calls[0][1]).toEqual({ priority: 20 })
  })
  it('pauses scheduling when concurrency changes and never sends OAuth in an edit', async () => {
    const wrapper = create(true)
    updateAccount.mockResolvedValue(account({ concurrency: 4, slot_binding_stale: true, schedulable: false }))
    await wrapper.findAll('input[type="number"]')[0].setValue('4')
    expect(wrapper.text()).toContain('rebindWarning')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(updateAccount.mock.calls[0][1]).toEqual({ concurrency: 4, schedulable: false })
    expect(wrapper.find('textarea').exists()).toBe(false)
  })
  it('sends lease imports with no selected group for server-side automatic allocation', async () => {
    const wrapper = create()
    importAccount.mockResolvedValue(account({ mode: 'lease' }))
    await wrapper.find('input').setValue('Lease account')
    await chooseProxy(wrapper)
    await wrapper.get('select').setValue('lease')
    await wrapper.get('textarea').setValue('{"refresh_token":"test-refresh"}')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(importAccount.mock.calls[0][0]).toMatchObject({ mode: 'lease', group_ids: [] })
  })
  it('exchanges browser OAuth and imports the resulting credential into the pool', async () => {
    generateAuthUrl.mockResolvedValue({ auth_url: 'https://auth.example.test/?state=state-1', session_id: 'session-1' })
    exchangeCode.mockResolvedValue({ access_token: 'access-only', refresh_token: 'refresh-only', id_token: 'id-only', expires_at: 123 })
    importAccount.mockResolvedValue(account())
    const wrapper = create()
    await wrapper.find('input').setValue('Browser OAuth account')
    await chooseProxy(wrapper)
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await flushPromises()
    expect(generateAuthUrl).toHaveBeenCalledWith('/admin/openai/generate-auth-url', {})
    await wrapper.get('[data-testid="oauth-code-input"]').setValue('http://localhost/callback?code=code-1&state=state-1')
    await flushPromises()
    await wrapper.get('[data-testid="oauth-complete"]').trigger('click')
    await flushPromises()
    expect(exchangeCode).toHaveBeenCalledWith('/admin/openai/exchange-code', { session_id: 'session-1', code: 'code-1', state: 'state-1' })
    expect(importAccount.mock.calls[0][0].credential).toEqual({ access_token: 'access-only', refresh_token: 'refresh-only', id_token: 'id-only', expires_at: 123 })
    expect(wrapper.emitted('saved')).toHaveLength(1)
  })
  it('discards a late authorization URL after the dialog is closed and reopened', async () => {
    let resolve!: (value: { auth_url: string; session_id: string }) => void
    generateAuthUrl.mockReturnValue(new Promise(value => { resolve = value }))
    const wrapper = create()
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await wrapper.get('[data-testid="account-pool-close"]').trigger('click')
    await wrapper.setProps({ show: false })
    await wrapper.setProps({ show: true })
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    resolve({ auth_url: 'https://auth.example.test/?state=old-state', session_id: 'old-session' })
    await flushPromises()
    expect(wrapper.find('a').exists()).toBe(false)
    expect(wrapper.get('[data-testid="oauth-complete"]').attributes('disabled')).toBeDefined()
    expect(importAccount).not.toHaveBeenCalled()
  })
  it('does not import tokens from a late exchange after close or display the old error', async () => {
    let resolve!: (value: Record<string, unknown>) => void
    generateAuthUrl.mockResolvedValue({ auth_url: 'https://auth.example.test/?state=state-1', session_id: 'session-1' })
    exchangeCode.mockReturnValue(new Promise(value => { resolve = value }))
    const wrapper = create()
    await wrapper.find('input').setValue('Browser account')
    await chooseProxy(wrapper)
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await flushPromises()
    await wrapper.get('[data-testid="oauth-code-input"]').setValue('code-1')
    await wrapper.get('[data-testid="oauth-complete"]').trigger('click')
    await wrapper.get('[data-testid="account-pool-close"]').trigger('click')
    await wrapper.setProps({ show: false })
    await wrapper.setProps({ show: true })
    resolve({ access_token: 'late-secret' })
    await flushPromises()
    expect(importAccount).not.toHaveBeenCalled()
    expect(wrapper.emitted('saved')).toBeUndefined()
    expect(wrapper.text()).not.toContain('late-secret')
    expect(wrapper.find('[role="alert"]').exists()).toBe(false)
  })
  it('rejects callback state mismatch and clears old codes when regenerating a session', async () => {
    generateAuthUrl.mockResolvedValue({ auth_url: 'https://auth.example.test/?state=state-1', session_id: 'session-1' })
    const wrapper = create()
    await wrapper.find('input').setValue('Browser account')
    await chooseProxy(wrapper)
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await flushPromises()
    await wrapper.get('[data-testid="oauth-code-input"]').setValue('http://localhost/callback?code=code-1&state=other-state')
    await wrapper.get('[data-testid="oauth-complete"]').trigger('click')
    expect(exchangeCode).not.toHaveBeenCalled()
    expect(wrapper.text()).toContain('oauthStateMismatch')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await flushPromises()
    expect((wrapper.get('[data-testid="oauth-code-input"]').element as HTMLTextAreaElement).value).toBe('')
    expect(wrapper.get('[data-testid="oauth-complete"]').attributes('disabled')).toBeDefined()
  })
  it('retries failed imports without reusing the consumed code and clears cached tokens on close', async () => {
    generateAuthUrl.mockResolvedValue({ auth_url: 'https://auth.example.test/?state=state-1', session_id: 'session-1' })
    exchangeCode.mockResolvedValue({ access_token: 'access-secret' })
    importAccount.mockRejectedValueOnce(new Error('access-secret')).mockResolvedValueOnce(account())
    const wrapper = create()
    await wrapper.find('input').setValue('Browser account')
    await chooseProxy(wrapper)
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await flushPromises()
    await wrapper.get('[data-testid="oauth-code-input"]').setValue('code-1')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.text()).toContain('oauthImportFailed')
    expect(wrapper.text()).not.toContain('access-secret')
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
    const key = importAccount.mock.calls[0][1]
    await wrapper.get('[data-testid="oauth-complete"]').trigger('click')
    await flushPromises()
    expect(exchangeCode).toHaveBeenCalledTimes(1)
    expect(importAccount).toHaveBeenCalledTimes(2)
    expect(importAccount.mock.calls[1][1]).toBe(key)
    expect(wrapper.emitted('saved')).toHaveLength(1)
    expect(wrapper.find('[data-testid="oauth-code-input"]').exists()).toBe(false)
  })
  it('accepts callback query strings and prevents duplicate exchange while a request is pending', async () => {
    generateAuthUrl.mockResolvedValue({ auth_url: 'https://auth.example.test/?state=state-1', session_id: 'session-1' })
    exchangeCode.mockReturnValue(new Promise(() => {}))
    const wrapper = create()
    await wrapper.find('input').setValue('Browser account')
    await chooseProxy(wrapper)
    await wrapper.get('[data-testid="oauth-mode-browser"]').trigger('click')
    await wrapper.get('[data-testid="oauth-generate"]').trigger('click')
    await flushPromises()
    await wrapper.get('[data-testid="oauth-code-input"]').setValue('?code=code-1&state=state-1')
    await wrapper.get('form').trigger('submit')
    await wrapper.get('form').trigger('submit')
    expect(exchangeCode).toHaveBeenCalledTimes(1)
    expect(exchangeCode.mock.calls[0][1]).toEqual({ session_id: 'session-1', code: 'code-1', state: 'state-1' })
    expect(wrapper.get('[data-testid="oauth-complete"]').attributes('disabled')).toBeDefined()
  })
})
